# 26. Assign a value to 'marks', then reassign a new value.
#     Show value before and after reassignment.

marks = 75
print("Before reassignment, marks =", marks)

marks = 88
print("After reassignment, marks =", marks)

# Explanation: A variable in Python is just a name (label) given to a
# value. When we reassign 'marks', the name now points to the new value
# (88), and the old value (75) is no longer accessible through 'marks'.
