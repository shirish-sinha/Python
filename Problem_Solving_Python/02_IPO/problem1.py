# IPO Model
# Input   : num1, num2
# Process : add num1 and num2
# Output  : print the sum

# Dry Run
# case 1:
#   num1 = 5, num2 = 3
#   sum = 5 + 3 = 8
#   Output: 8
#
# case 2:
#   num1 = -2, num2 = 10
#   sum = -2 + 10 = 8
#   Output: 8

num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

sum = num1 + num2

print("The sum is:", sum)
