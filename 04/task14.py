# Task 14 - Boolean Arithmetic Expressions

print("True + 5 =", True + 5)
print("False + 5 =", False + 5)
print("True * 10 =", True * 10)
print("False * 10 =", False * 10)
print("True - 5 =", True - 5)
print("False - 5 =", False - 5)

# Explanation:
# Since True behaves as 1 and False behaves as 0 in arithmetic,
# these expressions are equivalent to:
#   1 + 5 = 6
#   0 + 5 = 5
#   1 * 10 = 10
#   0 * 10 = 0
#   1 - 5 = -4
#   0 - 5 = -5
