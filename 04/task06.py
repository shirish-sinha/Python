# Task 6 - Division and Floor Division
# Normal division and floor division, tested with positive and negative numbers.

# --- Positive numbers ---
pos_num1 = 17
pos_num2 = 5

pos_division = pos_num1 / pos_num2
pos_floor_division = pos_num1 // pos_num2

print("Positive Numbers:", pos_num1, "and", pos_num2)
print("Division:", pos_division)
print("Floor Division:", pos_floor_division)

print()

# --- Negative numbers ---
neg_num1 = -17
neg_num2 = 5

neg_division = neg_num1 / neg_num2
neg_floor_division = neg_num1 // neg_num2

print("Negative Numbers:", neg_num1, "and", neg_num2)
print("Division:", neg_division)
print("Floor Division:", neg_floor_division)
