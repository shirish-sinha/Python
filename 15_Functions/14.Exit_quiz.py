# 1. What is a function?
# A function is a named block of code that performs a task.
#
# 2. Why do we use functions?
# Functions organize code, reduce repetition, and make code reusable.
#
# 3. What is code reuse?
# Code reuse means using the same code more than once instead of duplicating it.
#
# 4. Does defining a function automatically execute its body?
# No. The function body runs only when the function is called.
#
# 5. What does def do?
# The def keyword defines a function.
#
# 6. What is a function body?
# It is the indented code that belongs to a function.
#
# 7. Why is indentation important?
# Indentation shows which statements belong to the function body.
#
# 8. What is the difference between defining and calling a function?
# Defining creates the function. Calling it runs the function body.
#
# 9. How do you call a function named display_menu?
# Write display_menu().
#
# 10. Why should function names describe their task?
# Descriptive names make code easier to understand.
#
# 11. What naming style is commonly used for Python functions?
# Use lowercase words separated by underscores, called snake_case.
#
# 12. What happens if a function is called before its definition has executed?
# A NameError occurs because the function name is not defined yet.
#
# 13. How many times does a function body run if it is called four times?
# The function body runs four times.
#
# 14. Is Print_Total a valid Python function name? Is it the usual style?
# It is valid, but print_total follows the usual snake_case style.
#
# 15. Why might a function make a program easier to maintain?
# Shared code can be changed in one place instead of in multiple copies.
