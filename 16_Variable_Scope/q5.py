# Scope is the part of the module where our variable can be accessed, it is of 3 types:

# Global Scope: Can be accessed throughout the ModuleNotFoundError
# Local Scope: Can be accessed only inside the function
# Non-Local Scope: Can be accessed in the inner function and the parent function but not globally

# Lifetime of a variable is the part of the file inside which the binding of a variable stays to an object. After the function ends, the binding is removed from the object