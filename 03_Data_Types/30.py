a = 10
b = 10.0
c = "10"
d = True
e = "True"
f = None
g = "None"

print(a, type(a))   # 10 is an integer, type is int
print(b, type(b))   # 10.0 is a floating-point number, type is float
print(c, type(c))   # "10" is text inside quotes, type is str
print(d, type(d))   # True is a real Boolean value, type is bool
print(e, type(e))   # "True" is text inside quotes, type is str
print(f, type(f))   # None represents no value, type is NoneType
print(g, type(g))   # "None" is text inside quotes, type is str
